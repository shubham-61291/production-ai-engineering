import logging
import os
from google.cloud import storage
from google.cloud import logging as gcp_logging
from app.core.config import settings
from fpdf import FPDF
from app.models.schemas import AuditReport

def setup_logging():
    handlers = [logging.StreamHandler()]
    if settings.ENVIRONMENT == "production" and settings.GCP_PROJECT_ID:
        try:
            client = gcp_logging.Client(project=settings.GCP_PROJECT_ID)
            handler = gcp_logging.handlers.CloudLoggingHandler(client)
            handlers.append(handler)
        except Exception as e:
            logging.error(f"Failed to set up GCP logging: {e}")
    logging.basicConfig(
        level=logging.INFO,
        format='{"timestamp":"%(asctime)s","level":"%(levelname)s","module":"%(name)s","message":"%(message)s"}',
        handlers=handlers
    )

def upload_to_gcs(local_path: str, destination_blob_name: str) -> str:
    if not settings.GCS_BUCKET_NAME:
        raise ValueError("GCS_BUCKET_NAME not set")
    client = storage.Client(project=settings.GCP_PROJECT_ID)
    bucket = client.bucket(settings.GCS_BUCKET_NAME)
    blob = bucket.blob(destination_blob_name)
    blob.upload_from_filename(local_path)
    return f"https://storage.googleapis.com/{settings.GCS_BUCKET_NAME}/{destination_blob_name}"

def clean_text(text):
    if not isinstance(text, str):
        text = str(text or "")
    replacements = {
        '\u2018': "'", '\u2019': "'",
        '\u201c': '"', '\u201d': '"',
        '\u2013': '-', '\u2014': '-',
        '\u2026': '...'
    }
    for orig, repl in replacements.items():
        text = text.replace(orig, repl)
    return text.encode('latin-1', 'replace').decode('latin-1')

class MagnetarPDF(FPDF):
    def header(self):
        self.set_font('Helvetica', 'B', 15)
        self.cell(0, 10, 'MAGNETAR LEGAL AUDIT', 0, new_x="LMARGIN", new_y="NEXT", align='R')
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(128)
        self.cell(0, 10, f'Generated by Magnetar AI - Privileged & Confidential - Page {self.page_no()}', 0, 0, 'C')

def generate_audit_pdf(report_data: AuditReport, filename: str = None) -> str:
    if not filename:
        import uuid
        job_id = str(uuid.uuid4())
        filename = f"audit_{job_id}.pdf"
    os.makedirs(settings.REPORTS_DIR, exist_ok=True)
    filepath = os.path.join(settings.REPORTS_DIR, filename)

    pdf = MagnetarPDF()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.set_font('Helvetica', 'B', 12)
    pdf.set_fill_color(200, 220, 255)
    pdf.cell(0, 10, " EXECUTIVE SUMMARY", 1, new_x="LMARGIN", new_y="NEXT", align='L', fill=True)
    pdf.ln(2)
    pdf.set_font('Helvetica', '', 10)
    pdf.multi_cell(0, 6, clean_text(report_data.executive_summary))
    pdf.ln(5)

    score = report_data.overall_compliance_score
    color = (200, 50, 50) if score < 50 else (200, 160, 50) if score < 80 else (50, 150, 50)
    pdf.set_font('Helvetica', 'B', 12)
    pdf.set_text_color(*color)
    pdf.cell(0, 10, f"COMPLIANCE SCORE: {score}/100", 0, new_x="LMARGIN", new_y="NEXT", align='L')
    pdf.set_text_color(0)
    pdf.ln(5)

    pdf.set_font('Helvetica', 'B', 12)
    pdf.set_fill_color(255, 200, 200)
    pdf.cell(0, 10, " CRITICAL FINDINGS", 1, new_x="LMARGIN", new_y="NEXT", align='L', fill=True)
    pdf.ln(5)

    for flag in report_data.flagged_clauses:
        risk = (flag.risk_level or "MEDIUM").upper()
        pdf.set_font('Helvetica', 'B', 10)
        pdf.set_text_color(200, 0, 0)
        pdf.cell(0, 6, clean_text(f"[{risk}] Violation"), 0, new_x="LMARGIN", new_y="NEXT")
        pdf.set_text_color(0)
        pdf.set_font('Helvetica', 'I', 9)
        pdf.multi_cell(0, 5, clean_text(f"Clause: \"{flag.offending_clause}\""))
        pdf.ln(2)
        pdf.set_font('Helvetica', '', 9)
        pdf.multi_cell(0, 5, clean_text(f"Why: {flag.violation_explanation}"))
        pdf.ln(2)
        pdf.set_font('Helvetica', 'B', 9)
        pdf.set_text_color(0, 100, 0)
        pdf.multi_cell(0, 5, clean_text(f"Correction: {flag.suggested_rewrite}"))
        pdf.set_text_color(0)
        pdf.ln(5)
        pdf.line(10, pdf.get_y(), 200, pdf.get_y())
        pdf.ln(5)

    pdf.output(filepath)
    return filepath
